/**
 * Montenegrin municipalities: code for poziv na broj (model 18) and accounts of local revenues.
 * Naredba o načinu uplate javnih prihoda, Sl. list CG 23/26: čl. 3 (accounts) and Prilog 1 (codes).
 * Checked 2026-10, see docs/research.md §4.3 and §5.4. Every account passes mod 97 (tests/data.test.ts).
 */
export type LocalRevenue = 'prirez' | 'nepokretnosti' | 'adminTakse' | 'boravisna' | 'turisticka'

export interface Municipality {
  name: string
  code: string
  /** Official name as the payee: "Opština Bar", "Glavni grad Podgorica". */
  payee: string
  accounts: Partial<Record<LocalRevenue, string>>
}

/** An empty string in the tuple means the municipality has no such account (it is skipped). */
const m = (name: string, code: string, a: [string, string, string, string?, string?], payee = `Opština ${name}`): Municipality => ({
  name,
  code,
  payee,
  accounts: {
    prirez: a[0],
    ...(a[1] && { nepokretnosti: a[1] }),
    adminTakse: a[2],
    ...(a[3] && { boravisna: a[3] }),
    ...(a[4] && { turisticka: a[4] }),
  },
})

